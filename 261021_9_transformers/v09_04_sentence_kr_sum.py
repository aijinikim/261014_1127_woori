from transformers import pipeline
# pip install transformers==4.46.3

# 1. 요약 파이프라인
# t5-small 은 영어 전용 -> 한국어로 학습된 T5 요약 모델 사용 (한국어 입력 -> 한국어 요약)
summarizer = pipeline("summarization", model="eenzeenee/t5-base-korean-summarization")

# 2. 요약할 원문 (한국어 단락)
text = """
파울로 코엘료의 세계적인 베스트셀러 『연금술사』 출간 25주년을 기념한 특별판으로, 작가가 새로 쓴 서문이 함께 실려 있다.
마법과 신비, 지혜와 경이로움이 어우러진 이 자아 발견의 이야기는 전 세계에서 수백만 부가 팔리며 현대의 고전이 되었고, 여러 세대에 걸쳐 수많은 독자의 삶을 바꾸어 놓았다.
이야기의 주인공은 안달루시아의 양치기 소년 산티아고로, 그는 세상 어딘가에 숨겨진 보물을 찾아 여행을 떠나기를 꿈꾼다.
그의 여정은 처음 상상했던 것과는 전혀 다른, 그리고 훨씬 더 값진 보물로 그를 이끈다.
산티아고의 여행은 마음의 소리에 귀 기울이고, 기회를 알아보며, 삶의 길 위에 놓인 표지를 읽는 법, 그리고 무엇보다 자신의 꿈을 따르는 것의 소중함을 일깨워 준다.
"""

# 3. 요약 실행
summary = summarizer(
    text,
    min_length=20,  # 최소 토큰 수
    max_length=100, # 최대 토큰 수
    do_sample=False # 매번 동일 결과 출력
)

# 4. 결과 확인
sum_text = summary[0]["summary_text"]
print(f"요약된 문장 : {sum_text}")
"""
요약된 문장 : 산티아고의 여행은 마음의 소리에 귀 기울이고 기회를 알아보며 삶의 길 위에 놓인 표지를 읽는 법 자신의 꿈을 따르는 것의 소중함을 일깨워 준다.
"""